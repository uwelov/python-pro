# Множина: msgid -> (англійські форми, українські форми [one, few, many, other])
PLURALS = {
    "У кошику %(counter)s примірник": (
        ["%(counter)s copy in the cart", "%(counter)s copies in the cart"],
        ["У кошику %(counter)s примірник", "У кошику %(counter)s примірники",
         "У кошику %(counter)s примірників", "У кошику %(counter)s примірника"]),
    "«%(title)s»: у кошику %(count)d примірник": (
        ["“%(title)s”: %(count)d copy in the cart", "“%(title)s”: %(count)d copies in the cart"],
        ["«%(title)s»: у кошику %(count)d примірник", "«%(title)s»: у кошику %(count)d примірники",
         "«%(title)s»: у кошику %(count)d примірників", "«%(title)s»: у кошику %(count)d примірника"]),
}

def fill(lang, translate):
    path = f"locale/{lang}/LC_MESSAGES/django.po"
    po = polib.pofile(path)
    missing = []
    for e in po:
        if e.msgid_plural:
            en_forms, uk_forms = PLURALS[e.msgid]
            e.msgstr_plural = {i: f for i, f in enumerate(en_forms if lang == "en" else uk_forms)}
        else:
            value = translate(e.msgid)
            if value is None: missing.append(e.msgid)
            else: e.msgstr = value
        if "fuzzy" in e.flags: e.flags.remove("fuzzy")
    po.save(path)
    return missing

miss_en = fill("en", EN.get)
miss_uk = fill("uk", lambda m: m)
