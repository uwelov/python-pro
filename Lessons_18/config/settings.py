# Django Debug Toolbar
# https://django-debug-toolbar.readthedocs.io/en/latest/installation.html

INTERNAL_IPS = ['127.0.0.1']

if DEBUG:
    # У Docker запити приходять з IP шлюзу (напр. 172.18.0.1), а не з 127.0.0.1,
    # тому без цього тулбар у контейнері не відображається.
    try:
        _, _, _container_ips = socket.gethostbyname_ex(socket.gethostname())
        INTERNAL_IPS += [ip[: ip.rfind('.')] + '.1' for ip in _container_ips]
    except OSError:
        pass


